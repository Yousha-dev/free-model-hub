package admin

// This file implements the fallback login entry for "pasting the localhost authorization callback link".
//
// Trae / CodeArts upstream only accepts 127.0.0.1 callbacks. When the plugin and browser are on different machines (remote
// host, Docker, WSL), that callback can never reach, and the login gets stuck at "Waiting for authorization".
// The console explicitly displays the local callback address to the user. After the user completes authorization in the browser,
// they paste the entire link from the address bar back, and the plugin parses it locally to complete the login.

import (
	"net/http"
	"strings"

	"free-model-hub/cpasdk/pluginapi"
	"free-model-hub/internal/hostbridge"
	"free-model-hub/internal/logger"
)

// loginCallbackRequest represents a callback paste request.
type loginCallbackRequest struct {
	State string `json:"state"`
	URL   string `json:"url"`
}

// handleLoginCallbackRequest handles the localhost callback link pasted back by the user.
//
// Business failures (session expired, link mismatch, upstream not ready yet) uniformly return 200 + ok=false to
// the page: the page wants a reason that can be displayed directly rather than a status code—the error message is generated
// by the provider side, and has intentionally removed the callback link itself (which contains refreshToken / ticket secrets).
func (s *Service) handleLoginCallbackRequest(req pluginapi.ManagementRequest) pluginapi.ManagementResponse {
	body, errDecode := decodeRequest[loginCallbackRequest](req.Body)
	if errDecode != nil {
		// The page reads status / message according to the AuthLoginStatus contract. The generic
		// {ok, error} shape cannot be used here, otherwise the prompt "Please refresh the page and try again" will be lost.
		return JSONResponse(http.StatusBadRequest, map[string]any{
			"ok": false, "status": string(pluginapi.AuthLoginStatusError),
			"message": "Failed to parse request body, please refresh the page and try again",
		})
	}
	// Input parameter validation (non-empty state, non-empty URL) is uniformly handled by App.SubmitLoginCallback:
	// It is the only place that calls the provider, and putting validation here would require duplicating the code.
	ctx, cancel := hostbridge.ManagementContext(req, requestTimeout)
	defer cancel()

	result, errSubmit := s.deps.SubmitLoginCallback(ctx, body.State, body.URL)
	if errSubmit != nil {
		return JSONResponse(http.StatusOK, map[string]any{
			"ok": false, "status": string(pluginapi.AuthLoginStatusError),
			"message": errSubmit.Error(),
		})
	}

	status := result.Status
	payload := map[string]any{
		"ok":      status == pluginapi.AuthLoginStatusSuccess,
		"status":  string(status),
		"message": result.Message,
	}
	// CodeArts: When tickets have not yet been exchanged for credentials, the user still needs to open the Huawei Cloud login page in a new tab.
	if result.RedirectURL != "" {
		payload["redirect_url"] = result.RedirectURL
	}

	if status == pluginapi.AuthLoginStatusSuccess {
		// Credentials from the paste path only return to the **page**, and no one persists them for it—the normal polling path
		// writes files after auth.login.poll in the host, but there is no such host step here. Without this fallback,
		// the page shows "Login successful" but the auth directory remains empty.
		if errSave := saveAuthFile(hostbridge.RequestCallbackID(req), result.Auth.FileName, result.Auth.StorageJSON); errSave != nil {
			payload["ok"] = false
			payload["status"] = string(pluginapi.AuthLoginStatusError)
			payload["message"] = "Login completed, but failed to save credentials: " + errSave.Error()
			logger.Error("login callback persist failed (state=%s): %v", body.State, errSave)
			return JSONResponse(http.StatusOK, payload)
		}
		payload["auth_id"] = result.Auth.FileName
		payload["label"] = result.Auth.Label
	}

	// When persistence succeeds, saveAuthFile has already recorded an entry; here we only add an audit row for non-successful branches.
	if status != pluginapi.AuthLoginStatusSuccess {
		logger.Info("login callback handled (state=%s status=%s)", body.State, status)
	}
	return JSONResponse(http.StatusOK, payload)
}

// ---- SMS Code Login (SMSLoginProvider) ----
//
// The interaction contract is consistent with login/callback: the page reads results via {ok, status, message},
// and business failures return 200 instead of status codes—error messages are generated by the provider side and displayed directly by the page.

type loginSMSSendRequest struct {
	VendorID string `json:"vendor_id"`
	Phone    string `json:"phone"`
}

type loginSMSVerifyRequest struct {
	VendorID   string `json:"vendor_id"`
	SessionKey string `json:"session_key"`
	Phone      string `json:"phone"`
	Code       string `json:"code"`
	Label      string `json:"label"`
}

// handleLoginSMSSend handles "sending verification code".
func (s *Service) handleLoginSMSSend(req pluginapi.ManagementRequest) pluginapi.ManagementResponse {
	body, errDecode := decodeRequest[loginSMSSendRequest](req.Body)
	if errDecode != nil {
		return JSONResponse(http.StatusBadRequest, map[string]any{"ok": false, "message": "Failed to parse request body, please refresh the page and try again"})
	}
	ctx, cancel := hostbridge.ManagementContext(req, requestTimeout)
	defer cancel()
	sessionKey, errSend := s.deps.SendLoginSMS(ctx, strings.TrimSpace(body.VendorID), strings.TrimSpace(body.Phone))
	if errSend != nil {
		return JSONResponse(http.StatusOK, map[string]any{"ok": false, "message": errSend.Error()})
	}
	return JSONResponse(http.StatusOK, map[string]any{
		"ok": true, "session_key": sessionKey,
		"message": "Verification code sent, please check your SMS",
	})
}

// handleLoginSMSVerify handles "SMS code login": ticket exchange + persistence + reload.
func (s *Service) handleLoginSMSVerify(req pluginapi.ManagementRequest) pluginapi.ManagementResponse {
	body, errDecode := decodeRequest[loginSMSVerifyRequest](req.Body)
	if errDecode != nil {
		return JSONResponse(http.StatusBadRequest, map[string]any{"ok": false, "message": "Failed to parse request body, please refresh the page and try again"})
	}
	ctx, cancel := hostbridge.ManagementContext(req, requestTimeout)
	defer cancel()
	fileName, label, storageJSON, errVerify := s.deps.VerifyLoginSMS(ctx,
		strings.TrimSpace(body.VendorID), strings.TrimSpace(body.SessionKey),
		strings.TrimSpace(body.Phone), strings.TrimSpace(body.Code))
	if errVerify != nil {
		return JSONResponse(http.StatusOK, map[string]any{"ok": false, "message": errVerify.Error()})
	}
	if body.Label != "" {
		label = body.Label
	}
	if errSave := saveAuthFile(hostbridge.RequestCallbackID(req), fileName, []byte(storageJSON)); errSave != nil {
		return JSONResponse(http.StatusOK, map[string]any{"ok": false, "message": "Login successful, but failed to save credentials: " + errSave.Error()})
	}
	return JSONResponse(http.StatusOK, map[string]any{
		"ok": true, "auth_id": fileName, "label": label,
		"message": "Login successful, account added",
	})
}

// ---- In-Page Login (CAPTCHA → Authorization Link) ----
//
// Some providers' OAuth authorization address APIs mandatorily require browser-side CAPTCHA (AutoClaw Global
// edition Alibaba Cloud slider), and the token can only be generated in the user's browser. Therefore, the console first fetches widget parameters,
// lets the user drag the slider once, and then passes the obtained token to /login/start to exchange for the authorization address.
//
// Difference from the host's built-in <provider>-auth-url path: that path uniformly folds upstream errors into
// a single 500 ("failed to generate authorization url"), whereas what needs to be most understandable to users here
// is precisely "Slider expired, please drag again"—business failures uniformly return 200 + message to the page.

type loginStartRequest struct {
	VendorID string         `json:"vendor_id"`
	Metadata map[string]any `json:"metadata"`
}

// handleLoginStartRequest initiates a login and returns the authorization link.
func (s *Service) handleLoginStartRequest(req pluginapi.ManagementRequest) pluginapi.ManagementResponse {
	body, errDecode := decodeRequest[loginStartRequest](req.Body)
	if errDecode != nil {
		return JSONResponse(http.StatusBadRequest, map[string]any{
			"ok": false, "status": string(pluginapi.AuthLoginStatusError),
			"message": "Failed to parse request body, please refresh the page and try again",
		})
	}
	vendorID := strings.TrimSpace(body.VendorID)
	if vendorID == "" {
		return JSONResponse(http.StatusOK, map[string]any{
			"ok": false, "status": string(pluginapi.AuthLoginStatusError), "message": "missing provider ID",
		})
	}
	ctx, cancel := hostbridge.ManagementContext(req, requestTimeout)
	defer cancel()
	response, errStart := s.deps.StartLogin(ctx, vendorID, body.Metadata)
	if errStart != nil {
		return JSONResponse(http.StatusOK, map[string]any{
			"ok": false, "status": string(pluginapi.AuthLoginStatusError), "message": errStart.Error(),
		})
	}
	if response == nil || strings.TrimSpace(response.URL) == "" {
		return JSONResponse(http.StatusOK, map[string]any{
			"ok": false, "status": string(pluginapi.AuthLoginStatusError),
			"message": "The upstream did not return an authorization link, please try again",
		})
	}
	payload := map[string]any{
		"ok":    true,
		"url":   response.URL,
		"state": response.State,
	}
	if !response.ExpiresAt.IsZero() {
		payload["expires_at"] = response.ExpiresAt.Unix()
	}
	if response.Metadata != nil {
		if hint, okHint := response.Metadata["callback_hint"].(string); okHint && strings.TrimSpace(hint) != "" {
			payload["callback_hint"] = strings.TrimSpace(hint)
		}
	}
	return JSONResponse(http.StatusOK, payload)
}

// handleLoginCaptchaConfigRequest fetches the CAPTCHA widget parameters before login.
func (s *Service) handleLoginCaptchaConfigRequest(req pluginapi.ManagementRequest) pluginapi.ManagementResponse {
	vendorID := queryString(req.Query, "vendor")
	if vendorID == "" {
		return JSONResponse(http.StatusOK, map[string]any{"ok": false, "message": "missing vendor parameter"})
	}
	ctx, cancel := hostbridge.ManagementContext(req, requestTimeout)
	defer cancel()
	config, errConfig := s.deps.LoginCaptchaConfig(ctx, vendorID)
	if errConfig != nil {
		return JSONResponse(http.StatusOK, map[string]any{"ok": false, "message": errConfig.Error()})
	}
	return JSONResponse(http.StatusOK, map[string]any{"ok": true, "captcha": config})
}
