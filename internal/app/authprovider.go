package app

// This file implements auth provider capabilities:
//   - Credential identification/parsing/refresh and login distribution;
//   - Merged write-back of refreshed credentials (host hot-update + disk fallback).
//
// Login protocols and refresh chains are implemented by individual providers; the root layer only handles routing, error classification, and status code mapping.

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"

	"free-model-hub/cpasdk/pluginapi"
	"free-model-hub/internal/core"
	"free-model-hub/internal/hostbridge"
	"free-model-hub/internal/logger"
)

const (
	// authRefreshInterval is the next refresh interval after a successful credential verification.
	authRefreshInterval = 30 * time.Minute
	// authRefreshRetryAfter is the retry interval when encountering jitter/transient errors.
	authRefreshRetryAfter = 5 * time.Minute
	// authRefreshHTTPTimeout is the request limit for refresh verification.
	authRefreshHTTPTimeout = 60 * time.Second
	// credentialCacheTTL is the cache duration for credential source lookups.
	//
	// Credential rotation is mainly driven by the host (it passes the new StorageJSON to each capability).
	// The cache here mainly serves management page polling: 30 seconds is enough to be useful while timely reflecting account switches.
	credentialCacheTTL = 30 * time.Second
)

// authParseRPCRequest aligns with the host's auth.parse request.
type authParseRPCRequest struct {
	pluginapi.AuthParseRequest
	HostCallbackID string `json:"host_callback_id,omitempty"`
}

// authRefreshRPCRequest aligns with the host's auth.refresh request.
type authRefreshRPCRequest struct {
	pluginapi.AuthRefreshRequest
	HostCallbackID string `json:"host_callback_id,omitempty"`
}

// handleAuthParse identifies and parses credential files for this plugin.
//
// Ownership determination is delegated to core.ResolveVendor (three tiers: vendor field -> file name prefix -> content sniffing),
// and parsing itself is delegated to the matched provider instance. This way, adding new providers does not require modifying this code.
//
// It must neither miss its own files nor mistakenly swallow another provider's credentials—swallowing would cause the host
// to overwrite the other party's account with this plugin's structure silently.
func (a *App) handleAuthParse(request []byte) ([]byte, error) {
	var rpc authParseRPCRequest
	if errDecode := decodeRequest(request, &rpc); errDecode != nil {
		return nil, core.NewPluginError("invalid_request", errDecode.Error(), http.StatusBadRequest)
	}
	if len(rpc.RawJSON) == 0 {
		return core.OKEnvelope(pluginapi.AuthParseResponse{Handled: false})
	}

	var raw map[string]any
	if errUnmarshal := json.Unmarshal(rpc.RawJSON, &raw); errUnmarshal != nil {
		// Non-JSON credential files are not handled by this plugin.
		return core.OKEnvelope(pluginapi.AuthParseResponse{Handled: false})
	}

	vendor, okVendor := a.registry.Resolve(rpc.FileName, rpc.Provider, raw)
	if !okVendor {
		return core.OKEnvelope(pluginapi.AuthParseResponse{Handled: false})
	}

	credential, errCredential := vendor.Parse(rpc.RawJSON, rpc.FileName)
	if errCredential != nil {
		return nil, core.NewPluginError("credential_invalid", errCredential.Error(), http.StatusUnprocessableEntity)
	}

	logger.Info("parsed auth %s (vendor=%s)",
		core.FirstNonEmpty(credential.LabelValue(), rpc.FileName, rpc.Path), vendor.ID())

	auth, errAuth := buildAuthDataFor(vendor, credential, rpc.FileName, rpc.RawJSON)
	if errAuth != nil {
		return nil, errAuth
	}
	return core.OKEnvelope(pluginapi.AuthParseResponse{Handled: true, Auth: auth})
}

// buildAuthDataFor constructs credential records for the host contract (vendor-agnostic).
//
// fileName is determined by the caller:
//   - auth.parse uses the original file name passed by the host (does not rename files existing for users);
//   - auth.login.poll uses <vendor>-<uid>.json generated by core.FileNameFor.
func buildAuthDataFor(vendor core.Vendor, credential *core.Credential, fileName string, storageJSON []byte) (pluginapi.AuthData, error) {
	id := strings.TrimSuffix(fileName, ".json")
	if id == "" {
		// Fallback to account identity (file name); upstream UID is not an identity and should not appear here.
		id = credential.FileIDValue()
	}
	storage, errStorage := ensureVendorField(storageJSON, vendor.ID())
	if errStorage != nil {
		return pluginapi.AuthData{}, errStorage
	}
	// The StorageJSON returned to the host must be consistent with disk writes and the next refresh:
	// the host relies on it. Upon saving, un-normalized UIDs will derive a second account again (see hostbridge.AlignCredentialUID).
	storage = hostbridge.AlignCredentialUID(storage, fileName)
	return pluginapi.AuthData{
		Provider:    providerKey,
		ID:          id,
		FileName:    fileName,
		Label:       credential.LabelValue(),
		StorageJSON: storage,
		Metadata:    credentialMetadata(credential, vendor.ID()),
		Attributes:  credentialAttributes(credential, vendor.ID()),
		// Let the host trigger a refresh verification shortly after startup.
		NextRefreshAfter: time.Now().Add(authRefreshInterval),
	}, nil
}

// ensureVendorField ensures the credential JSON contains the vendor field.
//
// This is the **strongest evidence** of vendor ownership: the file name might be renamed by the user, but the vendor field is
// written by the plugin itself. Without it, user-renamed credentials can only rely on content sniffing for ownership,
// which is unreliable for structurally similar providers (both WorkBuddy and Qoder have a token field).
func ensureVendorField(storageJSON []byte, vendorID string) ([]byte, error) {
	if len(storageJSON) == 0 {
		return storageJSON, nil
	}
	var payload map[string]any
	if errUnmarshal := json.Unmarshal(storageJSON, &payload); errUnmarshal != nil {
		// Return as-is if parsing fails: credential content is the provider's responsibility, no forced modifications here.
		return storageJSON, nil
	}
	if existing, okExisting := payload[core.VendorKey].(string); okExisting &&
		strings.EqualFold(strings.TrimSpace(existing), vendorID) {
		return storageJSON, nil
	}
	payload[core.VendorKey] = vendorID
	merged, errMarshal := json.MarshalIndent(payload, "", "  ")
	if errMarshal != nil {
		return nil, fmt.Errorf("encode vendor field: %w", errMarshal)
	}
	return merged, nil
}

// credentialMetadata is the mutable metadata returned to the host.
//
// refresh_token must be here (see file header comments); the token itself is never returned.
func credentialMetadata(credential *core.Credential, vendorID string) map[string]any {
	metadata := map[string]any{
		core.VendorKey: vendorID,
		"realm":        credential.RegionValue(),
	}
	if uid := credential.FileIDValue(); uid != "" {
		metadata["uid"] = uid
	}
	if label := credential.LabelValue(); label != "" {
		metadata["nickname"] = label
	}
	if refreshToken := credential.RefreshTokenValue(); refreshToken != "" {
		metadata["refresh_token"] = refreshToken
		metadata["auth_mode"] = "oauth"
	}
	if expiresAt := credential.ExpiresAtValue(); expiresAt > 0 {
		metadata["expires_at"] = expiresAt
	}
	return metadata
}

// credentialAttributes are immutable attributes returned to the host (containing no credential material).
func credentialAttributes(credential *core.Credential, vendorID string) map[string]string {
	attributes := map[string]string{
		core.VendorKey: vendorID,
		"realm":        credential.RegionValue(),
	}
	if uid := credential.FileIDValue(); uid != "" {
		attributes["uid"] = uid
	}
	if label := credential.LabelValue(); label != "" {
		attributes["nickname"] = label
	}
	if credential.RefreshTokenValue() != "" {
		attributes["auth_mode"] = "oauth"
	}
	return attributes
}

// handleAuthRefresh verifies credentials and refreshes them when necessary.
//
// Refresh logic is **delegated to the provider owning the credential**: renewal chains vary greatly among providers
// (WorkBuddy uses X-Refresh-Token to exchange for a token, Qoder uses jobToken exchange),
// and the only commonalities are the three disposal policies: "invalidate credentials on error, retain on jitter, write back on success".
//
// Errors are handled in three categories:
//   - Credentials genuinely invalid (401/403) -> return error, letting the host mark the account as bad;
//   - Upstream jitter/unknown error -> Keep the original credential and assign a shorter next refresh time (avoid false positives on accounts);
//   - Success -> If the upstream rotated the token, write back the new credential.
func (a *App) handleAuthRefresh(request []byte) ([]byte, error) {
	var rpc authRefreshRPCRequest
	if errDecode := decodeRequest(request, &rpc); errDecode != nil {
		return nil, core.NewPluginError("invalid_request", errDecode.Error(), http.StatusBadRequest)
	}
	ctx, cancel := context.WithTimeout(hostbridge.WithCallbackID(context.Background(), rpc.HostCallbackID), authRefreshHTTPTimeout)
	defer cancel()

	credential, errCredential := a.credentialForAuth(ctx, rpc.HostCallbackID, rpc.StorageJSON, rpc.AuthID, rpc.Attributes)
	if errCredential != nil {
		return nil, core.NewPluginError("credential_missing", errCredential.Error(), http.StatusUnauthorized)
	}
	vendor, okVendor := a.registry.ByID(credential.VendorIDValue())
	if !okVendor {
		return nil, core.NewPluginError("credential_missing",
			"credential has no resolvable vendor", http.StatusUnauthorized)
	}

	updated, refreshed, errRefresh := core.RefreshVendor(vendor, ctx, credential)
	if errRefresh != nil {
		if isCredentialRejected(errRefresh) {
			logger.Error("auth refresh rejected for %s: %v", rpc.AuthID, errRefresh)
			return nil, core.ToPluginError(errRefresh)
		}
		// Jitter or unknown error: keep original credential, retry later.
		logger.Debug("auth refresh deferred for %s: %v", rpc.AuthID, errRefresh)
		auth, errData := a.refreshedAuthData(rpc, rpc.StorageJSON, credential)
		if errData != nil {
			return nil, errData
		}
		return core.OKEnvelope(pluginapi.AuthRefreshResponse{
			Auth:             auth,
			NextRefreshAfter: time.Now().Add(authRefreshRetryAfter),
		})
	}

	// Do not rewrite the file when the upstream did not issue a new token: otherwise mtime changes meaninglessly,
	// preventing users from determining whether the account has actually been refreshed based on file time.
	storage := rpc.StorageJSON
	if refreshed {
		if merged, errStorage := mergeVendorStorage(rpc.StorageJSON, updated, vendor); errStorage == nil {
			storage = merged
		}
	}
	logger.Info("auth refresh succeeded for %s (vendor=%s refreshed=%t)", rpc.AuthID, vendor.ID(), refreshed)
	auth, errData := a.refreshedAuthData(rpc, storage, updated)
	if errData != nil {
		return nil, errData
	}
	return core.OKEnvelope(pluginapi.AuthRefreshResponse{
		Auth:             auth,
		NextRefreshAfter: time.Now().Add(authRefreshInterval),
	})
}

// mergeVendorStorage merges the refreshed credential back into the original StorageJSON.
//
// The merge logic is **delegated to the provider itself** (via the optional core.StorageMerger interface): each provider's JSON
// structure differs (WorkBuddy has nested auth/account, Qoder has flat fields, Cline has flat
// accessToken/refreshToken), and a generic merge would mess up top-level fields.
//
// Returns as-is if the provider hasn't implemented this interface: better to do nothing than overwrite user files with an incorrect structure.
// Appends the vendor field after merging to ensure provider ownership is always determinable.
func mergeVendorStorage(original []byte, credential *core.Credential, vendor core.Vendor) ([]byte, error) {
	merger, okMerger := vendor.(core.StorageMerger)
	if !okMerger {
		return original, nil
	}
	merged, errMerge := merger.MergeStorageJSON(original, credential)
	if errMerge != nil {
		return nil, errMerge
	}
	return ensureVendorField(merged, vendor.ID())
}

// refreshedAuthData reconstructs the credential record after a refresh, preserving existing host-side fields.
//
// The provider is taken from the credential's own vendor field/region (in a refresh scenario the credential already exists,
// and ownership is definitely determinable), so the caller does not need to pass it again.
func (a *App) refreshedAuthData(rpc authRefreshRPCRequest, storageJSON []byte, credential *core.Credential) (pluginapi.AuthData, error) {
	vendor, okVendor := a.registry.ByID(credential.VendorIDValue())
	if !okVendor {
		return pluginapi.AuthData{}, fmt.Errorf("unknown vendor %q", credential.VendorIDValue())
	}
	data, errData := buildAuthDataFor(vendor, credential, rpc.AuthID, storageJSON)
	if errData != nil {
		return pluginapi.AuthData{}, errData
	}
	// Keep the identifier fields passed by the host to avoid loss due to plugin reconstruction.
	if strings.TrimSpace(rpc.AuthID) != "" {
		data.ID = rpc.AuthID
	}
	return data, nil
}

// isCredentialRejected reports whether an error indicates that the credential is truly invalid.
//
// The determination is based on the provider-classified HTTP status code (401/403 invalid credential, 402 quota exhausted),
// so it applies to all providers, rather than only recognizing WorkBuddy error types.
func isCredentialRejected(err error) bool {
	var upstream core.UpstreamError
	if !errors.As(err, &upstream) {
		return false
	}
	switch upstream.HTTPStatus() {
	case http.StatusUnauthorized, http.StatusForbidden, http.StatusPaymentRequired:
		return true
	}
	return false
}

// credentialCacheEntry is a cache entry for credential source-fetching.
type credentialCacheEntry struct {
	credential *core.Credential
	fetchedAt  time.Time
}

// credentialForAuth retrieves the credential for a given account.
//
// Prefers the StorageJSON sent by the host with the request (most accurate), falling back to source-fetching by auth_index when missing.
//
// **Source-fetching must be supported**: the host's management quota routing only sends AuthIndex/AuthID +
// Metadata/Attributes, **not StorageJSON**; whereas the plugin design does not put tokens into
// metadata/attributes, so relying solely on StorageJSON would misreport quota queries as "missing credential".
//
// Provider ownership is determined by the credential itself (vendor field -> filename -> content sniffing),
// so the caller does not need to specify a provider here, and adding a new provider does not require modifying this function.
func (a *App) credentialForAuth(ctx context.Context, callbackID string, storageJSON []byte, authID string, attributes map[string]string) (*core.Credential, error) {
	if len(storageJSON) > 0 {
		if credential, okParse := a.registry.ParseCredential(storageJSON, authID, attributes); okParse {
			return credential, nil
		}
	}
	if trimmed := strings.TrimSpace(authID); trimmed != "" {
		if cached, okCache := a.cachedCredential(trimmed); okCache {
			return cached, nil
		}
		raw, errFetch := hostbridge.FetchAuthJSON(ctx, callbackID, trimmed, a.registry)
		if errFetch == nil && len(raw) > 0 {
			if credential, okParse := a.registry.ParseCredential(raw, trimmed, attributes); okParse {
				a.storeCredential(trimmed, credential)
				return credential, nil
			}
		}
	}
	return nil, fmt.Errorf("credential is not available for auth %s", authID)
}

func (a *App) cachedCredential(authID string) (*core.Credential, bool) {
	a.credentialMu.Lock()
	defer a.credentialMu.Unlock()
	entry, okEntry := a.credentialCache[authID]
	if !okEntry || time.Since(entry.fetchedAt) > credentialCacheTTL {
		return nil, false
	}
	return entry.credential, true
}

func (a *App) storeCredential(authID string, credential *core.Credential) {
	a.credentialMu.Lock()
	defer a.credentialMu.Unlock()
	a.credentialCache[authID] = credentialCacheEntry{credential: credential, fetchedAt: time.Now()}
}

// resolveVendorCredential retrieves the credential and resolves its associated provider.
//
// Combining "fetching credential" and "determining provider" into one step: almost all ABI handlers need this pair,
// writing them separately would duplicate VendorByID + error handling everywhere.
func (a *App) resolveVendorCredential(ctx context.Context, callbackID string, storageJSON []byte, authID string, attributes map[string]string) (*core.Credential, core.Vendor, error) {
	credential, errCredential := a.credentialForAuth(ctx, callbackID, storageJSON, authID, attributes)
	if errCredential != nil {
		return nil, nil, core.NewPluginError("credential_missing", errCredential.Error(), http.StatusUnauthorized)
	}
	vendor, okVendor := a.registry.ByID(credential.VendorIDValue())
	if !okVendor {
		return nil, nil, core.NewPluginError("credential_missing",
			"credential has no resolvable vendor", http.StatusUnauthorized)
	}
	return credential, vendor, nil
}

// ---- Login Dispatch (formerly auth_login.go) ----

const (
	// loginHTTPTimeout is the limit for a single login-related request.
	loginHTTPTimeout = 30 * time.Second
)

// loginStartRPCRequest aligns with the host's auth.login.start request.
type loginStartRPCRequest struct {
	pluginapi.AuthLoginStartRequest
	HostCallbackID string `json:"host_callback_id,omitempty"`
}

// loginPollRPCRequest aligns with the host's auth.login.poll request.
type loginPollRPCRequest struct {
	pluginapi.AuthLoginPollRequest
	HostCallbackID string `json:"host_callback_id,omitempty"`
}

// handleAuthLoginStart initiates a login and returns the authorization URL the user needs to open.
//
// The login protocol is implemented by the provider; the root layer only handles provider routing and region switch validation.
func (a *App) handleAuthLoginStart(request []byte) ([]byte, error) {
	var rpc loginStartRPCRequest
	if errDecode := decodeRequest(request, &rpc); errDecode != nil {
		return nil, core.NewPluginError("invalid_request", errDecode.Error(), http.StatusBadRequest)
	}
	vendor, errVendor := a.vendorForLogin(rpc.Metadata)
	if errVendor != nil {
		return nil, errVendor
	}

	ctx, cancel := context.WithTimeout(hostbridge.WithCallbackID(context.Background(), rpc.HostCallbackID), loginHTTPTimeout)
	defer cancel()

	response, errStart := a.startVendorLogin(ctx, vendor, rpc.Metadata)
	if errStart != nil {
		return nil, errStart
	}
	logger.Info("started login (vendor=%s)", vendor.ID())
	return core.OKEnvelope(response)
}

// StartLogin initiates a provider login (console page path).
//
// Shared with the host <provider>-auth-url call via startVendorLogin, the only difference is the entry point:
// The page path must be able to obtain readable errors given by the provider (e.g., "Slider verification expired, drag again"),
// so it is handled by the plugin's own management route rather than bypassing it via the host's forwarding path which only returns 500.
func (a *App) StartLogin(ctx context.Context, vendorID string, metadata map[string]any) (*pluginapi.AuthLoginStartResponse, error) {
	vendor, okVendor := a.registry.ByID(strings.TrimSpace(vendorID))
	if !okVendor {
		return nil, core.NewPluginError("vendor_not_found", "vendor not found: "+vendorID, http.StatusNotFound)
	}
	if !a.vendorEnabled(vendor) {
		return nil, core.NewPluginError("vendor_disabled",
			fmt.Sprintf("vendor %s is disabled by plugin configuration", vendor.ID()), http.StatusBadRequest)
	}
	response, errStart := a.startVendorLogin(ctx, vendor, metadata)
	if errStart != nil {
		return nil, errStart
	}
	logger.Info("started login via console (vendor=%s)", vendor.ID())
	return response, nil
}

// LoginCaptchaConfig retrieves the CAPTCHA control parameters before login.
func (a *App) LoginCaptchaConfig(ctx context.Context, vendorID string) (core.CaptchaConfig, error) {
	vendor, okVendor := a.registry.ByID(strings.TrimSpace(vendorID))
	if !okVendor {
		return core.CaptchaConfig{}, core.NewPluginError("vendor_not_found", "vendor not found: "+vendorID, http.StatusNotFound)
	}
	if !a.vendorEnabled(vendor) {
		return core.CaptchaConfig{}, core.NewPluginError("vendor_disabled",
			fmt.Sprintf("vendor %s is disabled by plugin configuration", vendor.ID()), http.StatusBadRequest)
	}
	provider, okCaptcha := core.As[core.LoginCaptchaProvider](vendor)
	if !okCaptcha {
		return core.CaptchaConfig{}, core.NewPluginError("captcha_unsupported",
			vendor.Name()+" login does not require in-page CAPTCHA", http.StatusBadRequest)
	}
	config, errConfig := provider.LoginCaptchaConfig(ctx)
	if errConfig != nil {
		return core.CaptchaConfig{}, core.ToPluginError(errConfig)
	}
	return config, nil
}

// startVendorLogin is the shared implementation for the two login entry points (host auth-url / plugin management route).
//
// The vendor identifier is injected here: the host binds the login session back to the specific vendor via metadata.vendor,
// without it the host cannot get the authorization link, and the page will only see "Failed to get authorization link".
func (a *App) startVendorLogin(ctx context.Context, vendor core.Vendor, metadata map[string]any) (*pluginapi.AuthLoginStartResponse, error) {
	login, okLogin := core.As[core.LoginProvider](vendor)
	if !okLogin {
		return nil, core.LoginUnsupported(vendor)
	}
	if errLimit := a.pool.CheckVendorLimit(ctx, hostbridge.CallbackID(ctx), vendor, ""); errLimit != nil {
		return nil, errLimit
	}
	response, errStart := login.LoginStart(ctx, metadata)
	if errStart != nil {
		return nil, core.ToPluginError(errStart)
	}
	if response != nil {
		if response.Metadata == nil {
			response.Metadata = map[string]any{}
		}
		response.Metadata[core.VendorKey] = vendor.ID()
		response.Metadata["region"] = vendor.Region()
	}
	return response, nil
}

// handleAuthLoginPoll polls the login status once.
//
// Session state is maintained by the vendors themselves (respective state structures differ), and the root layer does not participate.
func (a *App) handleAuthLoginPoll(request []byte) ([]byte, error) {
	var rpc loginPollRPCRequest
	if errDecode := decodeRequest(request, &rpc); errDecode != nil {
		return nil, core.NewPluginError("invalid_request", errDecode.Error(), http.StatusBadRequest)
	}
	sessionID := strings.TrimSpace(rpc.State)
	if sessionID == "" {
		return nil, core.NewPluginError("invalid_request", "login state is required", http.StatusBadRequest)
	}
	vendor, errVendor := a.vendorForLoginSession(sessionID)
	if errVendor != nil {
		return nil, errVendor
	}

	ctx, cancel := context.WithTimeout(hostbridge.WithCallbackID(context.Background(), rpc.HostCallbackID), loginHTTPTimeout)
	defer cancel()

	login, okLogin := core.As[core.LoginProvider](vendor)
	if !okLogin {
		return nil, core.LoginUnsupported(vendor)
	}
	response, errPoll := login.LoginPoll(ctx, sessionID)
	if errPoll != nil {
		return nil, core.ToPluginError(errPoll)
	}
	if response != nil && response.Status == pluginapi.AuthLoginStatusSuccess {
		if errLimit := a.pool.CheckVendorLimit(ctx, rpc.HostCallbackID, vendor, response.Auth.FileName); errLimit != nil {
			return core.OKEnvelope(&pluginapi.AuthLoginPollResponse{
				Status:  pluginapi.AuthLoginStatusError,
				Message: errLimit.Error(),
			})
		}
	}
	return core.OKEnvelope(response)
}

// vendorForLogin resolves the target vendor from the login request's Metadata.
//
// The console page puts the vendor identifier chosen by the user into the vendor field of Metadata;
// when missing, it falls back to the first enabled vendor in the configuration (for compatibility with legacy pages passing only realm).
func (a *App) vendorForLogin(metadata map[string]any) (core.Vendor, error) {
	if metadata != nil {
		if rawVendor, okVendor := metadata[core.VendorKey].(string); okVendor {
			vendor, okLookup := a.registry.ByID(rawVendor)
			if !okLookup {
				return nil, core.NewPluginError("invalid_request",
					fmt.Sprintf("unknown vendor %q", rawVendor), http.StatusBadRequest)
			}
			if !a.vendorEnabled(vendor) {
				return nil, core.NewPluginError("vendor_disabled",
					fmt.Sprintf("vendor %s is disabled by plugin configuration", vendor.ID()), http.StatusBadRequest)
			}
			return vendor, nil
		}
		// Legacy page passing only realm: find the first matching vendor by region.
		if rawRegion, okRegion := metadata["region"].(string); okRegion && strings.TrimSpace(rawRegion) != "" {
			if vendor, okFind := a.firstVendorForRegion(rawRegion); okFind {
				return vendor, nil
			}
		}
	}
	if vendor, okDefault := a.firstEnabledVendor(); okDefault {
		return vendor, nil
	}
	return nil, core.NewPluginError("vendor_disabled", "no vendor is enabled by plugin configuration", http.StatusBadRequest)
}

// vendorForLoginSession finds the vendor by login session.
//
// Two ownership paths: first check the public session registry (core.LoginSessions); if not found, ask each
// vendor one by one "is this session yours" (core.LoginSessionOwner).
//
// The second is a prerequisite for the Trae family: they store sessions in their own SessionStore (callback listening requires
// instance isolation) and are not registered in the public table. Without this self-proof, Trae's login polling is always judged as
// "session not found", while users see "Authorization failed: login session not found or expired" in the console.
// Here we still do not guess the vendor by session ID prefix—guessing the prefix wrongly would route the session to another.
func (a *App) vendorForLoginSession(sessionID string) (core.Vendor, error) {
	if vendorID, okOwns := a.logins.Owns(sessionID); okOwns {
		if vendor, okVendor := a.registry.ByID(vendorID); okVendor {
			return vendor, nil
		}
	}
	for _, vendor := range a.registry.Vendors() {
		owner, okOwner := core.As[core.LoginSessionOwner](vendor)
		if okOwner && owner.OwnsLoginSession(sessionID) {
			return vendor, nil
		}
	}
	return nil, core.NewPluginError("session_not_found", "Login session does not exist or has expired, please restart login", http.StatusNotFound)
}

// SendLoginSMS sends an SMS verification code (vendorID locates the instance implementing SMSLoginProvider).
func (a *App) SendLoginSMS(ctx context.Context, vendorID, phone string) (string, error) {
	vendor, okVendor := a.registry.ByID(vendorID)
	if !okVendor {
		return "", core.NewPluginError("vendor_not_found", "vendor not found: "+vendorID, http.StatusNotFound)
	}
	sender, okSMS := core.As[core.SMSLoginProvider](vendor)
	if !okSMS {
		return "", core.NewPluginError("sms_unsupported", vendor.Name()+" does not support mobile verification code login", http.StatusBadRequest)
	}
	callbackID := hostbridge.CallbackID(ctx)
	if errLimit := a.pool.CheckVendorLimit(ctx, callbackID, vendor, ""); errLimit != nil {
		return "", errLimit
	}
	sessionKey, errSend := sender.SendLoginCode(ctx, phone)
	if errSend != nil {
		return "", core.ToPluginError(errSend)
	}
	return sessionKey, nil
}

// VerifyLoginSMS completes login using the SMS verification code and returns the persistent credential JSON.
func (a *App) VerifyLoginSMS(ctx context.Context, vendorID, sessionKey, phone, code string) (string, string, string, error) {
	vendor, okVendor := a.registry.ByID(vendorID)
	if !okVendor {
		return "", "", "", core.NewPluginError("vendor_not_found", "vendor not found: "+vendorID, http.StatusNotFound)
	}
	sender, okSMS := core.As[core.SMSLoginProvider](vendor)
	if !okSMS {
		return "", "", "", core.NewPluginError("sms_unsupported", vendor.Name()+" does not support mobile verification code login", http.StatusBadRequest)
	}
	storageJSON, label, errVerify := sender.VerifyLoginCode(ctx, sessionKey, phone, code)
	if errVerify != nil {
		return "", "", "", core.ToPluginError(errVerify)
	}
	// Filename generated based on account identity: UID → display name → credential fingerprint (fallback for core.FileNameFor).
	// Display names can duplicate and be empty; relying solely on it as the filename is the cause of "the second account overwriting the first"
	// (#55); the fingerprint also needs the access token as a seed, which is passed to FileNameFor together here.
	identifier, token := label, ""
	if credential, errParse := vendor.Parse(storageJSON, ""); errParse == nil {
		identifier = core.FirstNonEmpty(credential.UIDValue(), label)
		token = credential.TokenValue()
	}
	fileName := core.FileNameFor(vendor.ID(), identifier, token)
	return fileName, label, string(storageJSON), nil
}

// SubmitLoginCallback handles the localhost callback link pasted back from the console.
//
// Supported only by vendors implementing core.CallbackSubmitter (Trae family and CodeArts): upstream
// only recognizes localhost callbacks, and when the plugin and browser are not on the same machine, that callback can never arrive.
// Users paste back the full URL where the browser stopped, and the plugin parses it on the spot to complete the login.
func (a *App) SubmitLoginCallback(ctx context.Context, state, rawURL string) (*core.CallbackSubmitResult, error) {
	sessionID := strings.TrimSpace(state)
	if sessionID == "" {
		return nil, core.NewPluginError("invalid_request", "Missing login session state, please restart login", http.StatusBadRequest)
	}
	vendor, errVendor := a.vendorForLoginSession(sessionID)
	if errVendor != nil {
		return nil, errVendor
	}
	submitter, okSubmit := core.As[core.CallbackSubmitter](vendor)
	if !okSubmit {
		return nil, core.NewPluginError("callback_unsupported",
			vendor.Name()+" login does not rely on local callbacks, no need to paste callback link", http.StatusBadRequest)
	}

	trimmed := strings.TrimSpace(rawURL)
	if trimmed == "" {
		return nil, core.NewPluginError("invalid_request", "Please paste the complete callback link from the browser address bar", http.StatusBadRequest)
	}

	callbackID := hostbridge.CallbackID(ctx)
	if errLimit := a.pool.CheckVendorLimit(ctx, callbackID, vendor, ""); errLimit != nil {
		return nil, errLimit
	}
	result, errSubmit := submitter.SubmitCallback(ctx, sessionID, trimmed)
	if errSubmit != nil {
		return nil, core.ToPluginError(errSubmit)
	}
	if result == nil {
		return nil, core.NewPluginError("login_failed", "Callback processing failed, please restart login", http.StatusInternalServerError)
	}
	if result.Status == pluginapi.AuthLoginStatusSuccess {
		if errLimit := a.pool.CheckVendorLimit(ctx, callbackID, vendor, result.Auth.FileName); errLimit != nil {
			return nil, errLimit
		}
	}
	return result, nil
}

// vendorEnabled reports whether the vendor's region is enabled in the configuration.
func (a *App) vendorEnabled(vendor core.Vendor) bool {
	return core.RealmEnabled(a.Config().EnabledRealms, vendor.Region())
}

// firstEnabledVendor returns the first enabled vendor in the configuration.
func (a *App) firstEnabledVendor() (core.Vendor, bool) {
	for _, vendor := range a.registry.Vendors() {
		if a.vendorEnabled(vendor) {
			return vendor, true
		}
	}
	return nil, false
}

// firstVendorForRegion returns the first enabled vendor for a given region.
func (a *App) firstVendorForRegion(region string) (core.Vendor, bool) {
	normalized := strings.ToLower(strings.TrimSpace(region))
	for _, vendor := range a.registry.Vendors() {
		if vendor.Region() == normalized && a.vendorEnabled(vendor) {
			return vendor, true
		}
	}
	return nil, false
}

// ---- Credential Write-Back (formerly credentials.go) ----

// saveRefreshedCredential writes the refreshed credential back to the host and disk.
//
// Writing to two places is a deliberate double insurance:
//   - host.auth.save allows the host to hot-update the in-memory registry;
//   - Directly write to file as a fallback when host.auth.save is unavailable.
//
// Both places must write the **same** content: uid case normalization is handled
// uniformly by hostbridge.SaveAuth / hostbridge.AlignCredentialUID (see notes there);
// this function only selects the correct base name for normalization and writes the returned JSON to disk as-is.
func (a *App) saveRefreshedCredential(ctx context.Context, callbackID string, vendor core.Vendor,
	entry core.HostAuth, original []byte, updated *core.Credential, filePath string) {
	payload, okPayload := refreshedStorageJSON(vendor, original, updated)
	targetPath := filePath
	if targetPath == "" {
		targetPath = entry.Path
	}
	if targetPath == "" {
		return
	}
	name := authWriteName(entry, targetPath)
	if okPayload {
		// SaveAuth performs uid normalization internally and returns the JSON actually written to the host.
		saved, errSave := hostbridge.SaveAuth(callbackID, name, payload)
		if errSave != nil {
			logger.Debug("keepalive %s: host.auth.save failed: %v", entry.Name, errSave)
		}
		payload = saved
	} else {
		// Normalization is required even if merging fails: unnormalized credentials would otherwise be registered as an extra entry by the host based on uid.
		payload = hostbridge.AlignCredentialUID(payload, name)
	}
	// Temp file + rename: The credential file is watched by the host via fsnotify, and a half-written state causes the host to read a
	// truncated JSON. rename is atomic within the same filesystem, so the host will only see either the old or the new version.
	tmp := targetPath + ".tmp"
	if errWrite := os.WriteFile(tmp, payload, 0o600); errWrite != nil {
		logger.Debug("keepalive %s: write credential file failed: %v", entry.Name, errWrite)
		return
	}
	if errRename := os.Rename(tmp, targetPath); errRename != nil {
		_ = os.Remove(tmp)
		logger.Debug("keepalive %s: replace credential file failed: %v", entry.Name, errRename)
	}
}

// authWriteName returns the base filename used when normalizing the uid.
//
// The host provides two sources for the same account: Name is the registration key, and Path is the physical file; their casing
// may differ. The registration key is the spelling used by the host for deduplication, so it takes precedence; fall back to
// the disk filename to be written if Name is missing (otherwise nobody will recognize the normalized spelling).
func authWriteName(entry core.HostAuth, targetPath string) string {
	if name := strings.TrimSpace(entry.Name); name != "" {
		return name
	}
	return filepath.Base(targetPath)
}

// refreshedStorageJSON updates the credential JSON using the provider's own merge logic.
func refreshedStorageJSON(vendor core.Vendor, original []byte, updated *core.Credential) ([]byte, bool) {
	merger, okMerger := vendor.(core.StorageMerger)
	if !okMerger {
		return original, false
	}
	merged, errMerge := merger.MergeStorageJSON(original, updated)
	if errMerge != nil {
		return original, false
	}
	return merged, true
}
